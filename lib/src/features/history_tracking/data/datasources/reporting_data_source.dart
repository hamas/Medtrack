import 'dart:typed_data';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../../../medication_management/domain/entities/adherence_log.dart';
import '../../../medication_management/domain/entities/medicine.dart';

class ReportingService {
  ReportingService._();

  /// Generates a comprehensive clinical report across all medicines or a single medicine
  static Future<void> generateComprehensiveReport({
    required String patientName,
    required List<Medicine> medicines,
    required List<AdherenceLog> logs,
  }) async {
    final pw.Document pdf = pw.Document();
    final DateFormat dateFormat = DateFormat('MMM dd, yyyy - hh:mm a');

    final int totalTaken = logs
        .where((AdherenceLog l) => l.status == AdherenceStatus.taken)
        .length;
    final int totalSkipped = logs
        .where((AdherenceLog l) => l.status == AdherenceStatus.skipped)
        .length;
    final double adherenceRate = logs.isEmpty
        ? 100.0
        : (totalTaken / (totalTaken + totalSkipped)) * 100.0;

    final List<AdherenceLog> sideEffectLogs = logs
        .where(
          (AdherenceLog l) =>
              l.mealNotes != null && l.mealNotes!.contains('Side Effect:'),
        )
        .toList();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) {
          return <pw.Widget>[
            // Clinical Header
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: <pw.Widget>[
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: <pw.Widget>[
                    pw.Text(
                      'CLINICAL ADHERENCE REPORT',
                      style: const pw.TextStyle(
                        fontSize: 20,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.blue900,
                      ),
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text(
                      'Generated by Medtrack Clinical Management Engine',
                      style: const pw.TextStyle(
                        fontSize: 10,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: <pw.Widget>[
                    pw.Text(
                      'Date: ${DateFormat('yyyy-MM-dd').format(DateTime.now())}',
                      style: const pw.TextStyle(fontSize: 10),
                    ),
                    pw.Text(
                      'Patient: $patientName',
                      style: const pw.TextStyle(
                        fontSize: 11,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                  ],
                ),
              ],
            ),
            pw.SizedBox(height: 16),
            pw.Divider(thickness: 1, color: PdfColors.blue900),

            // Adherence KPI Summary Card
            pw.Container(
              padding: const pw.EdgeInsets.all(12),
              decoration: pw.BoxDecoration(
                color: PdfColors.grey100,
                borderRadius: pw.BorderRadius.circular(8),
              ),
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
                children: <pw.Widget>[
                  pw.Column(
                    children: <pw.Widget>[
                      pw.Text(
                        'Active Meds',
                        style: const pw.TextStyle(
                          fontSize: 10,
                          color: PdfColors.grey700,
                        ),
                      ),
                      pw.Text(
                        '${medicines.length}',
                        style: const pw.TextStyle(
                          fontSize: 16,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                    ],
                  ),
                  pw.Column(
                    children: <pw.Widget>[
                      pw.Text(
                        'Doses Taken',
                        style: const pw.TextStyle(
                          fontSize: 10,
                          color: PdfColors.grey700,
                        ),
                      ),
                      pw.Text(
                        '$totalTaken',
                        style: const pw.TextStyle(
                          fontSize: 16,
                          fontWeight: pw.FontWeight.bold,
                          color: PdfColors.green800,
                        ),
                      ),
                    ],
                  ),
                  pw.Column(
                    children: <pw.Widget>[
                      pw.Text(
                        'Doses Skipped',
                        style: const pw.TextStyle(
                          fontSize: 10,
                          color: PdfColors.grey700,
                        ),
                      ),
                      pw.Text(
                        '$totalSkipped',
                        style: const pw.TextStyle(
                          fontSize: 16,
                          fontWeight: pw.FontWeight.bold,
                          color: PdfColors.red800,
                        ),
                      ),
                    ],
                  ),
                  pw.Column(
                    children: <pw.Widget>[
                      pw.Text(
                        'Adherence Rate',
                        style: const pw.TextStyle(
                          fontSize: 10,
                          color: PdfColors.grey700,
                        ),
                      ),
                      pw.Text(
                        '${adherenceRate.toStringAsFixed(1)}%',
                        style: const pw.TextStyle(
                          fontSize: 16,
                          fontWeight: pw.FontWeight.bold,
                          color: PdfColors.blue800,
                        ),
                      ),
                    ],
                  ),
                ],
              ),
            ),
            pw.SizedBox(height: 20),

            // Medication Prescriptions Table
            pw.Text(
              'Active Medication Regimen',
              style: const pw.TextStyle(
                fontSize: 14,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 8),
            pw.TableHelper.fromTextArray(
              headers: <String>[
                'Medication',
                'Dosage',
                'Frequency',
                'Times',
                'Remaining',
              ],
              data: medicines.map((Medicine m) {
                return <String>[
                  m.name,
                  m.dosage,
                  m.intervalType.name.toUpperCase(),
                  m.scheduleTimes.join(', '),
                  '${m.remainingQuantity} units',
                ];
              }).toList(),
              headerStyle: const pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
                fontSize: 10,
                color: PdfColors.white,
              ),
              headerDecoration: const pw.BoxDecoration(
                color: PdfColors.blue800,
              ),
              cellStyle: const pw.TextStyle(fontSize: 9),
              cellPadding: const pw.EdgeInsets.symmetric(
                vertical: 4,
                horizontal: 6,
              ),
            ),
            pw.SizedBox(height: 20),

            if (sideEffectLogs.isNotEmpty) ...<pw.Widget>[
              pw.Text(
                'Side Effects & Tolerability Observations',
                style: const pw.TextStyle(
                  fontSize: 14,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.red900,
                ),
              ),
              pw.SizedBox(height: 8),
              pw.TableHelper.fromTextArray(
                headers: <String>[
                  'Timestamp',
                  'Clinical Tolerability Observation',
                ],
                data: sideEffectLogs.map((AdherenceLog log) {
                  return <String>[
                    dateFormat.format(log.takenTime ?? log.scheduledTime),
                    log.mealNotes ?? '--',
                  ];
                }).toList(),
                headerStyle: const pw.TextStyle(
                  fontWeight: pw.FontWeight.bold,
                  fontSize: 10,
                  color: PdfColors.white,
                ),
                headerDecoration: const pw.BoxDecoration(
                  color: PdfColors.red800,
                ),
                cellStyle: const pw.TextStyle(fontSize: 9),
                cellPadding: const pw.EdgeInsets.symmetric(
                  vertical: 4,
                  horizontal: 6,
                ),
              ),
              pw.SizedBox(height: 20),
            ],

            // Adherence Intake Audit Logs
            pw.Text(
              'Recorded Dose Audit Log',
              style: const pw.TextStyle(
                fontSize: 14,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 8),
            if (logs.isEmpty)
              pw.Text(
                'No intake logs recorded yet.',
                style: const pw.TextStyle(
                  fontSize: 10,
                  color: PdfColors.grey600,
                ),
              )
            else
              pw.TableHelper.fromTextArray(
                headers: <String>['Scheduled Time', 'Status', 'Notes'],
                data: logs.take(50).map((AdherenceLog log) {
                  return <String>[
                    dateFormat.format(log.scheduledTime),
                    log.status.name.toUpperCase(),
                    log.mealNotes ?? '--',
                  ];
                }).toList(),
                headerStyle: const pw.TextStyle(
                  fontWeight: pw.FontWeight.bold,
                  fontSize: 10,
                  color: PdfColors.white,
                ),
                headerDecoration: const pw.BoxDecoration(
                  color: PdfColors.grey800,
                ),
                cellStyle: const pw.TextStyle(fontSize: 9),
                cellPadding: const pw.EdgeInsets.symmetric(
                  vertical: 4,
                  horizontal: 6,
                ),
              ),
          ];
        },
      ),
    );

    final Uint8List bytes = await pdf.save();
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => bytes,
      name: 'Medtrack_Clinical_Report_${patientName.replaceAll(' ', '_')}.pdf',
    );
  }

  static Future<void> generateAdherenceReport({
    required Medicine medicine,
    required List<AdherenceLog> logs,
  }) async {
    return generateComprehensiveReport(
      patientName: 'Patient',
      medicines: <Medicine>[medicine],
      logs: logs,
    );
  }
}
